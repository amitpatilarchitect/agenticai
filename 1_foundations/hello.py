print("Hello, World!")

def add(a, b):
    """Add two numbers 
    together.

    Args:
        a: The first number.
        b: The second number.

    Returns:
        The sum of the two numbers.
    """
    return a + b

print(add(1, 2))

def subtract(a, b):
    """Subtract two numbers."""
    return a - b

print(subtract(1, 2))

def multiply(a, b): 
    """Multiply two numbers."""
    return a * b

print(multiply(1, 2))

def divide(a, b):
    """Divide two numbers."""
    return a / b

print(divide(1, 2))